/**
 * Mandi catalogue.
 *
 * The government price feed carries no coordinates — only state, district and market
 * name — so distance, which is the whole basis of a net-price ranking, cannot come
 * from it. Every mandi we can place on a map is listed here with real coordinates and
 * with the three keys needed to pull its live prices back out of the feed.
 *
 * A mandi whose `agmarknetMarket` is null still works; it simply keeps whatever price
 * was last recorded by a field agent instead of refreshing from the feed.
 *
 * Commission and market fee are the deductions actually taken at the gate. Terminal
 * markets (Azadpur, Vashi, Pune) charge materially more than a district APMC, which is
 * exactly why a farmer needs them netted off before comparing.
 */
